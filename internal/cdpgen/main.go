// Command cdpgen generates Go bindings from the checked-in protocol snapshot.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type field struct {
	Name, Type, JSON string
	Optional         bool
}
type definition struct {
	Name, Kind, Event string
	Fields            []field
	Values            map[string]string
}
type command struct {
	Name, Method   string
	Params, Result []field
}
type domain struct {
	Name, File string
	Types      []definition
	Commands   []command
}
type protocol struct {
	Version string
	Domains []domain
}

func fields(b *strings.Builder, list []field) {
	for _, f := range list {
		tag := f.JSON
		if f.Optional {
			if strings.HasPrefix(f.Type, "[]") || strings.HasPrefix(f.Type, "map[") {
				tag += ",omitzero"
			} else {
				tag += ",omitempty"
			}
		}
		fmt.Fprintf(b, "\t%s %s `json:%q`\n", f.Name, f.Type, tag)
	}
}

func main() {
	spec := flag.String("spec", "cdp/protocol.json", "snapshot")
	out := flag.String("out", "cdp", "output directory")
	flag.Parse()
	raw, err := os.ReadFile(*spec)
	must(err)
	var p protocol
	must(json.Unmarshal(raw, &p))
	must(os.MkdirAll(*out, 0755))
	for _, d := range p.Domains {
		var b strings.Builder
		fmt.Fprintf(&b, "// Code generated by cdpgen from zendriver %s; DO NOT EDIT.\npackage cdp\n\n", p.Version)
		fmt.Fprintf(&b, "type %sCommands struct{}\nvar %s = %sCommands{}\n\n", d.Name, d.Name, d.Name)
		for _, t := range d.Types {
			if t.Kind == "struct" {
				fmt.Fprintf(&b, "type %s struct {\n", t.Name)
				fields(&b, t.Fields)
				b.WriteString("}\n")
			} else {
				fmt.Fprintf(&b, "type %s %s\n", t.Name, t.Kind)
				// Stable enum order is required for reproducible generation.
				names := make([]string, 0, len(t.Values))
				for n := range t.Values {
					names = append(names, n)
				}
				sort.Strings(names)
				for _, n := range names {
					fmt.Fprintf(&b, "const %s %s = %q\n", n, t.Name, t.Values[n])
				}
			}
			if t.Event != "" {
				fmt.Fprintf(&b, "func (%s) CDPEventName() string { return %q }\nconst %sEvent = %q\n", t.Name, t.Event, t.Name, t.Event)
			}
			b.WriteString("\n")
		}
		for _, c := range d.Commands {
			base := d.Name + c.Name
			if len(c.Params) > 0 {
				fmt.Fprintf(&b, "type %sParams struct {\n", base)
				fields(&b, c.Params)
				b.WriteString("}\n")
			}
			fmt.Fprintf(&b, "type %sResult struct {\n", base)
			fields(&b, c.Result)
			b.WriteString("}\n")
			if len(c.Params) > 0 {
				fmt.Fprintf(&b, "func (%sCommands) %s(params %sParams) Command[%sResult] { return Command[%sResult]{Method: %q, Params: params} }\n\n", d.Name, c.Name, base, base, base, c.Method)
			} else {
				fmt.Fprintf(&b, "func (%sCommands) %s() Command[%sResult] { return Command[%sResult]{Method: %q} }\n\n", d.Name, c.Name, base, base, c.Method)
			}
		}
		code, err := format.Source([]byte(b.String()))
		if err != nil {
			_ = os.WriteFile(filepath.Join(*out, d.File+"_gen.go"), []byte(b.String()), 0644)
			must(err)
		}
		must(os.WriteFile(filepath.Join(*out, d.File+"_gen.go"), code, 0644))
	}
	fmt.Printf("Generated %d CDP domains (%s)\n", len(p.Domains), p.Version)
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
